<h2>Using this site</h2>
<p>Final Decisions PLLC does not use tracking or analytics on this site. The site does not have contact forms, user logins, or comments. It has a search box; searches are sent as requests to the site.</p>
<h2>Theme preference</h2>
<p>If you choose a light or dark theme, the site stores that preference in your browser's local storage. The preference is not sent to the firm. You can remove it using your browser's storage controls.</p>
<h2>Hosting, requests, and search</h2>
<p>The site uses Bluehost WordPress Basic shared hosting. Bluehost retains logs of requests to the site for at least 30 days. A search sends the search terms in the URL, so those terms are included in Bluehost's request logs. The firm may archive or delete logs.</p>
<p>Cloudflare is enabled as a proxy and content delivery network (CDN) and handles requests to the site. According to Bluehost, this site uses Cloudflare’s Self-Serve/Free Tier network architecture. Cloudflare temporarily processes technical details, including IP address, browser type, and requested pages, for security and performance debugging. Bluehost describes the service as having a zero-retention policy, with individual technical access logs automatically overwritten or deleted within 4 to 24 hours. Search terms in URLs may also appear in browser history, CDN logs, or referrers.</p>
<h2>Contacting the firm</h2>
<p>If you contact the firm by email or mail, the firm may retain your name, contact information, and the contents of your communications. Contact records are kept for at least three years. The firm does not sell or disclose contact information unless legally required to do so.</p>
<p>For questions about this policy, contact the firm.</p>
