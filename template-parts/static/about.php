<p class="page-section__label">The founder</p>
<div>
<h2>Bryan Lammon</h2>
<p>Bryan Lammon founded Final Decisions PLLC in January 2025 to focus on federal civil appeals. Before opening the firm, he was a tenured law professor who taught litigation courses and wrote about federal appellate jurisdiction. He now represents parties on appeal and works with co-counsel on appellate questions and briefs.</p>
<p>In addition to his practice, Lammon is a Visiting Professor at William &amp; Mary Law School and the Director of its Appellate &amp; Supreme Court Clinic. Before that, he taught at the University of Toledo College of Law, Northern Illinois University College of Law, and Washington University School of Law. He left full-time law teaching in 2024.</p>
<p>Before becoming a law professor and starting his firm, Lammon practiced in the Issues &amp; Appeals group at Jones Day in Chicago and served as a law clerk to Judge Edward C. Prado of the U.S. Court of Appeals for the Fifth Circuit.</p>
<p>Lammon earned his J.D., summa cum laude, from Washington University School of Law in 2008, where he received the Alumni Association Award for the highest GPA in the graduating class. Lammon earned a B.A. in economics, cum laude, from the University of Notre Dame in 2005.</p>
